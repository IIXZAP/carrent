-- ============================================================
--  อัปเดตกฎการให้บริการ (4 ข้อ)
--
--  1. รับ–ส่งรถ 30 กม.แรกฟรี เกินคิดเหมาเป็นช่วงระยะ
--  2. รับ–คืนรถ 08:00–20:00 · สนามบิน 05:00–24:00
--  3. มัดจำการจอง 1,000 ทุกคัน (หักจากค่าเช่า) · เงินประกัน 3 ระดับ
--  4. เว้นระยะระหว่างการจองอย่างน้อย 4 ชั่วโมง
--
--  รันได้ทั้ง carrent และ carrent2 · รันซ้ำได้ไม่เสียหาย
--  ไม่ลบข้อมูลการจองหรือลูกค้าใดๆ
--
--  วิธีใช้: phpMyAdmin → เลือกฐานข้อมูล → Import → ไฟล์นี้
-- ============================================================
SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 1) ค่าตั้งใหม่
-- ------------------------------------------------------------
INSERT INTO settings (skey, svalue) VALUES

-- เวลาพักรถระหว่างงาน — จองติดกันเป๊ะไม่ได้ ต้องเว้นอย่างน้อยเท่านี้
('booking_gap_hours',   '4'),

-- เวลาทำการของสนามบิน (จุดอื่นใช้ open_time/close_time เดิม 08:00–20:00)
('airport_open_time',   '05:00'),
('airport_close_time',  '24:00'),

-- มัดจำการจอง — หักจากค่าเช่า ใช้เมื่อรถคันนั้นไม่ได้ตั้งค่าเฉพาะไว้
('booking_deposit',     '1000'),

-- ค่าเดินทางรับ–ส่งรถ
('free_delivery_km',    '30'),
-- รูปแบบ "ถึงกม.:ราคา" คั่นด้วยจุลภาค · แก้ได้เองที่ หลังบ้าน → ตั้งค่า
('delivery_tiers',      '30:0,50:500,80:1000,120:1500,200:2500')

ON DUPLICATE KEY UPDATE svalue = VALUES(svalue);

-- เวลาทำการปกติ — ตั้งให้ตรงกับกฎใหม่ (เผื่อเคยแก้ไว้เป็นค่าอื่น)
INSERT INTO settings (skey, svalue) VALUES
('open_time',  '08:00'),
('close_time', '20:00')
ON DUPLICATE KEY UPDATE svalue = VALUES(svalue);

-- ------------------------------------------------------------
-- 2) มัดจำการจอง 1,000 บาท เท่ากันทุกคัน
-- ------------------------------------------------------------
UPDATE cars SET deposit_booking = 1000;

-- ------------------------------------------------------------
-- 3) เงินประกันความเสียหาย 3 ระดับ
--      อีโคคาร์            3,000
--      ซีดาน / กระบะ       5,000
--      SUV / รถตู้        10,000
-- ------------------------------------------------------------
UPDATE cars SET deposit = 3000  WHERE car_type = 'eco';
UPDATE cars SET deposit = 5000  WHERE car_type IN ('sedan', 'pickup');
UPDATE cars SET deposit = 10000 WHERE car_type IN ('suv', 'van');

-- ------------------------------------------------------------
-- 4) ค่าส่งรถเดิมที่ตั้งไว้ต่อคัน ไม่ใช้แล้ว
--    ตอนนี้คิดตามระยะทางจากตาราง delivery_tiers แทน
--    ตั้งเป็น 0 ไว้กันสับสน (คอลัมน์ยังอยู่ เผื่ออยากกลับไปใช้แบบเดิม)
-- ------------------------------------------------------------
UPDATE cars SET delivery_fee = 0;

-- ============================================================
--  ตรวจผล
-- ============================================================
SELECT
  CONCAT(brand, ' ', model) AS 'รถ',
  car_type                  AS 'ประเภท',
  price_day                 AS 'ราคา/วัน',
  deposit_booking           AS 'มัดจำจอง',
  deposit                   AS 'เงินประกัน'
FROM cars ORDER BY deposit, price_day;

SELECT skey AS 'ค่าตั้ง', svalue AS 'ค่า' FROM settings
WHERE skey IN ('booking_gap_hours','open_time','close_time',
               'airport_open_time','airport_close_time',
               'booking_deposit','free_delivery_km','delivery_tiers')
ORDER BY FIELD(skey,'booking_gap_hours','open_time','close_time',
               'airport_open_time','airport_close_time',
               'booking_deposit','free_delivery_km','delivery_tiers');
